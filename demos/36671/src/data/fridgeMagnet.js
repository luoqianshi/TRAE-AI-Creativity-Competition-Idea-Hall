export function calculateStats(magnets, footprints) {
  const totalMagnets = magnets.length;
  const totalFootprints = footprints.length;

  const themes = new Set(magnets.map(m => m.theme));
  const materials = new Set(magnets.map(m => m.material));
  const origins = new Set(magnets.map(m => m.origin));

  const themeCounts = {};
  magnets.forEach(m => { themeCounts[m.theme] = (themeCounts[m.theme] || 0) + 1; });

  const materialCounts = {};
  magnets.forEach(m => { materialCounts[m.material] = (materialCounts[m.material] || 0) + 1; });

  const originCounts = {};
  magnets.forEach(m => { originCounts[m.origin] = (originCounts[m.origin] || 0) + 1; });

  const allDates = [...magnets, ...footprints].map(r => r.date).sort();
  let streakDays = 0;
  if (allDates.length > 0) {
    const today = new Date();
    const lastDate = new Date(allDates[allDates.length - 1]);
    const diff = Math.floor((today - lastDate) / 86400000);
    if (diff <= 1) {
      streakDays = 1;
      for (let i = allDates.length - 2; i >= 0; i--) {
        const curr = new Date(allDates[i + 1]);
        const prev = new Date(allDates[i]);
        const d = Math.floor((curr - prev) / 86400000);
        if (d === 1) streakDays++;
        else break;
      }
    }
  }

  return {
    totalMagnets,
    totalFootprints,
    themes,
    materials,
    origins,
    themeCounts,
    materialCounts,
    originCounts,
    streakDays,
  };
}
