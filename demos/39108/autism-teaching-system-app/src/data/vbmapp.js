/**
 * 获取指定领域和阶段的技能列表
 */
export function getSkillsForDomainLevel(domainKey, level) {
  return VB_MAPP_SKILLS[domainKey]?.[`level${level}`] || [];
}

/**
 * 获取指定领域的所有技能（三个阶段合并）
 */
export function getAllSkillsForDomain(domainKey) {
  const skills = [];
  [1, 2, 3].forEach((level) => {
    const levelSkills = VB_MAPP_SKILLS[domainKey]?.[`level${level}`] || [];
    levelSkills.forEach((skillName, idx) => {
      skills.push({
        code: `${domainKey}-L${level}-${idx + 1}`,
        description: skillName,
        level,
        domain: domainKey,
        domainName: VB_MAPP_DOMAINS[domainKey]?.name || domainKey,
      });
    });
  });
  return skills;
}

/**
 * 根据技能描述反查领域和阶段
 */
export function findSkillByDescription(description) {
  for (const [domainKey, levels] of Object.entries(VB_MAPP_SKILLS)) {
    for (const [levelKey, skills] of Object.entries(levels)) {
      const idx = skills.findIndex((s) => s === description);
      if (idx !== -1) {
        return {
          domainKey,
          domainName: VB_MAPP_DOMAINS[domainKey]?.name || domainKey,
          level: Number(levelKey.replace('level', '')),
          index: idx + 1,
          code: `${domainKey}-L${levelKey.replace('level', '')}-${idx + 1}`,
        };
      }
    }
  }
  return null;
}
