function getSpringFestival(year) {
  if (year < 1900 || year > 2100) {
    return estimateSpringFestival(year);
  }
  let totalDays = 0;
  for (let y = 1900; y < year; y++) {
    const code = LUNAR_INFO[y - 1900];
    let daysInYear = 0;
    for (let m = 0; m < 12; m++) {
      daysInYear += 29 + ((code >> (15 - m)) & 1);
    }
    const lm = code & 0xf;
    if (lm > 0) {
      daysInYear += 29 + ((code >> 16) & 1);
    }
    totalDays += daysInYear;
  }
  const jd = date2JD(1900, 1, 31, 0, 0) + totalDays;
  const result = JD2Date(jd);
  return { m: result.month, d: result.day };
}

function estimateSpringFestival(year) {
  const baseYear = 2000;
  const baseSpringJD = date2JD(2000, 2, 5, 0, 0);
  const yearDiff = year - baseYear;
  const estimatedJD = baseSpringJD + yearDiff * 354.367;
  const result = JD2Date(estimatedJD);
  return { m: result.month, d: result.day };
}

function solarToLunar(year, month, day) {
  if (year < 1900 || year > 2100) {
    return { lunarYear: year, lunarMonth: month, lunarDay: day, monthName: '', dayName: '', isLeap: false };
  }
  
  const spring = getSpringFestival(year);
  const springJD = date2JD(year, spring.m, spring.d, 0, 0);
  const targetJD = date2JD(year, month, day, 0, 0);
  
  let daysDiff = Math.floor(targetJD - springJD);
  
  if (daysDiff < 0) {
    const prevSpring = getSpringFestival(year - 1);
    const prevSpringJD = date2JD(year - 1, prevSpring.m, prevSpring.d, 0, 0);
    daysDiff = Math.floor(targetJD - prevSpringJD);
    year -= 1;
  }
  
  const code = LUNAR_INFO[year - 1900];
  const leapMonth = code & 0xf;
  let currentMonth = 1;
  let remainingDays = daysDiff;
  
  for (let m = 0; m < 12; m++) {
    const isLeap = leapMonth !== 0 && m + 1 === leapMonth;
    const daysInMonth = 29 + ((code >> (15 - m)) & 1);
    
    if (remainingDays < daysInMonth) {
      return {
        lunarYear: year,
        lunarMonth: isLeap ? -currentMonth : currentMonth,
        lunarDay: remainingDays + 1,
        monthName: (isLeap ? '闰' : '') + LUNAR_MONTH_NAMES[currentMonth],
        dayName: LUNAR_DAY_NAMES[remainingDays + 1],
        isLeap: isLeap
      };
    }
    
    remainingDays -= daysInMonth;
    
    if (!isLeap) {
      currentMonth++;
    }
    
    if (isLeap && remainingDays < (29 + ((code >> 16) & 1))) {
      return {
        lunarYear: year,
        lunarMonth: -currentMonth,
        lunarDay: remainingDays + 1,
        monthName: '闰' + LUNAR_MONTH_NAMES[currentMonth],
        dayName: LUNAR_DAY_NAMES[remainingDays + 1],
        isLeap: true
      };
    }
    
    if (isLeap) {
      remainingDays -= (29 + ((code >> 16) & 1));
      currentMonth++;
    }
  }
  
  return { lunarYear: year, lunarMonth: 12, lunarDay: remainingDays + 1, monthName: '腊月', dayName: LUNAR_DAY_NAMES[remainingDays + 1], isLeap: false };
}

