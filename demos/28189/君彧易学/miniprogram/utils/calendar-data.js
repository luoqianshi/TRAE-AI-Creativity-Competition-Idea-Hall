function daysInMonth(year, month) {
  if (month === 2) {
    return (year % 4 === 0 && year % 100 !== 0) || (year % 400 === 0) ? 29 : 28;
  }
  return [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][month - 1];
}

function JD2Date(jd) {
  let Z = Math.floor(jd + 0.5);
  let A = Z;
  if (Z >= 2299161) {
    let alpha = Math.floor((Z - 1867216.25) / 36524.25);
    A = Z + 1 + alpha - Math.floor(alpha / 4);
  }
  let B = A + 1524;
  let C = Math.floor((B - 122.1) / 365.25);
  let D = Math.floor(365.25 * C);
  let E = Math.floor((B - D) / 30.6001);
  let day = B - D - Math.floor(30.6001 * E);
  let month = E - 1;
  if (month > 12) month -= 12;
  let year = C - 4716;
  if (month <= 2) year -= 1;
  let dayFraction = jd + 0.5 - Z;
  if (dayFraction < 0) dayFraction += 1;
  let hour = Math.floor(dayFraction * 24);
  let minute = Math.floor((dayFraction * 24 - hour) * 60);
  return { year, month, day, hour, minute };
}

function date2JD(year, month, day, hour, minute) {
  hour = hour || 0;
  minute = minute || 0;
  let y = year, m = month;
  if (m <= 2) { y -= 1; m += 12; }
  let B = 0;
  if (year > 1582 || (year === 1582 && month > 10) || (year === 1582 && month === 10 && day >= 15)) {
    let A = Math.floor(y / 100);
    B = 2 - A + Math.floor(A / 4);
  }
  let jd = Math.floor(365.25 * (y + 4716)) + Math.floor(30.6001 * (m + 1)) + day + B - 1524.5;
  jd += hour / 24 + minute / 1440;
  return jd;
}

// ==================== 太阳黄经计算（备用） ====================

/**
 * 计算指定时刻的太阳视黄经（度）
 * 基于Meeus《天文算法》第25章
 * 精度：±0.01°，对应时间误差约±1分钟
 */
function sunLongitude(jd) {
  const T = (jd - 2451545.0) / 36525.0;
  const T2 = T * T;
  const T3 = T2 * T;
  
  const L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T2;
  const M = 357.52911 + 35999.05029 * T - 0.0001537 * T2;
  const M_rad = M * Math.PI / 180;
  const C = (1.914602 - 0.004817 * T - 0.000014 * T2) * Math.sin(M_rad)
          + (0.019993 - 0.000101 * T) * Math.sin(2 * M_rad)
          + 0.000289 * Math.sin(3 * M_rad);
  let lambda = L0 + C;
  // 行星摄动
  lambda += 0.000025 * Math.sin((119.0 + 303.0 * T) * Math.PI / 180);
  lambda += 0.000011 * Math.sin((34.0 + 31.0 * T) * Math.PI / 180);
  const M_moon = 134.9634 + 477198.8675 * T;
  lambda += 0.000028 * Math.sin(M_moon * Math.PI / 180);
  // 章动
  const omega = 125.04452 - 1934.136261 * T + 0.0020708 * T2 + T3 / 450000;
  lambda += -0.0048 * Math.sin(omega * Math.PI / 180) - 0.0004 * Math.sin(2 * omega * Math.PI / 180);
  // 光行差
  lambda -= 0.00569;
  lambda = ((lambda % 360) + 360) % 360;
  return lambda;
}

/**
 * 使用牛顿迭代法精确计算太阳到达指定黄经的时刻（备用）
 */
function solarTermJD(longitude, year, month) {
  const jieQiIndex = Math.round(((longitude - 285 + 360) % 360) / 15);
  const typicalDayOffsets = [
    5, 20, 34, 49, 64, 80,
    95, 110, 126, 141, 156, 172,
    187, 202, 218, 233, 249, 265,
    280, 295, 311, 326, 341, 356
  ];
  const dayOffset = typicalDayOffsets[jieQiIndex] || (jieQiIndex * 15.2);
  let jd = date2JD(year, 1, 1, 12, 0) + (dayOffset - 1);
  for (let i = 0; i < 20; i++) {
    let lng = sunLongitude(jd);
    let diff = lng - longitude;
    if (diff > 180) diff -= 360;
    if (diff < -180) diff += 360;
    if (Math.abs(diff) < 0.000001) break;
    const daysFromPerihelion = (jd - 2451545.0 + 3) % 365.25;
    const dailyMotion = 0.9856 + 0.0334 * Math.cos(daysFromPerihelion * 2 * Math.PI / 365.25);
    jd -= diff / dailyMotion;
  }
  return JD2Date(jd);
}

// ==================== 节气计算（主函数） ====================

/**
 * 获取某年的24节气
 * 优先使用预计算数据表，年份超出范围时回退到算法计算
 * 
 * @param {number} year - 年份
 * @returns {Array} [{ n: 名称, m: 月, d: 日, h: 时 }, ...]
 */
function getYearJieQi(year) {
  const result = [];
  const yearIndex = year - 1900;
  
  // 检查是否在预计算数据范围内
  if (yearIndex >= 0 && yearIndex < JIEQI_MD.length) {
    const mdStr = JIEQI_MD[yearIndex];
    
    for (let i = 0; i < 24; i++) {
      // 解析月日
      const mdPart = mdStr.substring(i * 4, i * 4 + 4);
      const month = parseInt(mdPart.substring(0, 2), 10);
      const day = parseInt(mdPart.substring(2, 4), 10);
      
      // 获取时辰
      let hour = 0;
      const correctionKey = year + '-' + i;
      if (JIEQI_HOUR_CORRECTION.hasOwnProperty(correctionKey)) {
        hour = JIEQI_HOUR_CORRECTION[correctionKey];
      } else {
        // 无修正数据时，使用算法计算
        const longitude = (285 + i * 15) % 360;
        const refMonth = Math.floor(i / 2) + 1;
        const calc = solarTermJD(longitude, year, refMonth > 12 ? 1 : refMonth);
        hour = calc.hour;
      }
      
      result.push({
        n: JIEQI_NAMES[i],
        m: month,
        d: day,
        h: hour
      });
    }
  } else {
    // 超出范围，回退到算法计算
    for (let i = 0; i < 24; i++) {
      const longitude = (285 + i * 15) % 360;
      const refMonth = Math.floor(i / 2) + 1;
      const actualMonth = refMonth > 12 ? 1 : refMonth;
      const dt = solarTermJD(longitude, year, actualMonth);
      result.push({
        n: JIEQI_NAMES[i],
        m: dt.month,
        d: dt.day,
        h: dt.hour
      });
    }
  }
  
  return result;
}

