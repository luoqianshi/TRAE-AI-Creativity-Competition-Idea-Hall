        kindergarten: ['幼儿园', '学前', '幼小', '启蒙', '宝宝', '小朋友'],
        primary: ['小学', '三年级', '四年级', '五年级', '六年级', '一年级', '二年级', '小升初', '小学数学'],
        junior: ['初中', '七年级', '八年级', '九年级', '初一', '初二', '初三', '中考'],
