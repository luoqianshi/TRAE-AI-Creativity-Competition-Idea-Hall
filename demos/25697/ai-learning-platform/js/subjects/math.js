                    question: 'sin ' + angle + '\u00b0 的值是？',
                    answer: sinVals[angle],
                    type: '选择题',
                    hint: '特殊角三角函数值',
                    options: ['A. ' + sinVals[angle], 'B. cos ' + angle + '\u00b0', 'C. tan ' + angle + '\u00b0', 'D. 1'],
